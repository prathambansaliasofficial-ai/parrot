/**
 * Exports the local SQLite database as D1-compatible SQL.
 *
 * Tables are emitted in foreign-key dependency order (computed from
 * PRAGMA foreign_key_list, not hand-written), so `wrangler d1 execute --file`
 * succeeds with foreign keys enforced.
 *
 *   node scripts/d1-export.mjs              # writes db/d1/data.sql
 *   node scripts/d1-export.mjs --verify     # also writes expected-counts.json
 */
import fs from "node:fs";
import path from "node:path";
import Database from "better-sqlite3";

const root = process.cwd();
const dbPath = process.env.DATABASE_PATH
  ? path.resolve(process.env.DATABASE_PATH)
  : path.join(root, "db", "freeresources.db");
// Data lives outside the migrations directory so `d1 migrations apply` never
// mistakes an import file for a schema migration.
const outDir = path.join(root, "db", "d1-data");
fs.mkdirSync(outDir, { recursive: true });
const textDir = path.join(outDir, "text");
fs.mkdirSync(textDir, { recursive: true });

const db = new Database(dbPath, { readonly: true });

const tables = db
  .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
  .all()
  .map((row) => row.name);

/** Topological sort by foreign-key dependency. */
const deps = new Map(tables.map((table) => [table, new Set()]));
for (const table of tables) {
  for (const fk of db.prepare(`PRAGMA foreign_key_list(${table})`).all()) {
    if (fk.table && fk.table !== table && deps.has(fk.table)) deps.get(table).add(fk.table);
  }
}
const ordered = [];
const seen = new Set();
const visiting = new Set();
function visit(table) {
  if (seen.has(table) || visiting.has(table)) return;
  visiting.add(table);
  for (const dep of deps.get(table)) visit(dep);
  visiting.delete(table);
  seen.add(table);
  ordered.push(table);
}
for (const table of tables) visit(table);
const skippedCycles = tables.filter((table) => !seen.has(table));
ordered.push(...skippedCycles);

function quote(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "bigint") return value.toString();
  if (value instanceof Uint8Array) return `X'${Buffer.from(value).toString("hex")}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  "-- D1 data import generated by scripts/d1-export.mjs.",
  "-- Restore of the local SQLite database. Run AFTER the schema migrations:",
  "--   npx wrangler d1 execute freeresources-dev --local --file=db/d1-data/data.sql",
  "--",
  "-- Extracted PDF text is NOT imported: D1 rows stay small and searchable",
  "-- metadata lives in the database while full document text belongs in R2.",
  "-- See db/d1-data/text/manifest.json and docs/CLOUDFLARE.md.",
  "",
  "PRAGMA defer_foreign_keys = true;",
  "",
];

const counts = {};
const textManifest = [];
let totalRows = 0;
let movedText = 0;
for (const table of ordered) {
  const rows = db.prepare(`SELECT * FROM ${table}`).all();
  counts[table] = rows.length;
  totalRows += rows.length;
  if (!rows.length) continue;
  const columns = Object.keys(rows[0]);
  lines.push(`-- ${table}: ${rows.length} row(s)`);
  for (const row of rows) {
    // Large extracted text is moved to R2; the row keeps a reference instead.
    if (table === "document_assets" && typeof row.text_content === "string" && row.text_content.length > 0) {
      const file = `${row.sha256}.txt`;
      fs.writeFileSync(path.join(textDir, file), row.text_content);
      textManifest.push({
        sha256: row.sha256,
        assetId: row.id,
        chars: row.text_content.length,
        r2Key: `text/${row.sha256.slice(0, 2)}/${row.sha256}.txt`,
        file: `text/${file}`,
      });
      movedText += 1;
      row.text_content = null;
    }
    const values = columns.map((column) => quote(row[column])).join(", ");
    lines.push(`INSERT OR REPLACE INTO ${table} (${columns.map((c) => `"${c}"`).join(", ")}) VALUES (${values});`);
  }
  lines.push("");
}

lines.push("PRAGMA defer_foreign_keys = false;", "");

fs.writeFileSync(path.join(outDir, "data.sql"), lines.join("\n"));
fs.writeFileSync(path.join(outDir, "expected-counts.json"), JSON.stringify(counts, null, 2));
fs.writeFileSync(path.join(textDir, "manifest.json"), JSON.stringify(textManifest, null, 2));

const longest = Math.max(...lines.map((line) => line.length));
console.log(`Exported ${totalRows} row(s) across ${ordered.filter((t) => counts[t] > 0).length} table(s).`);
console.log(`Moved ${movedText} extracted-text body/bodies to db/d1-data/text/ (R2 keys in manifest.json).`);
console.log(`Longest SQL statement: ${longest} chars.`);
console.log(`Wrote db/d1-data/data.sql + expected-counts.json (${ordered.length} tables known).`);
