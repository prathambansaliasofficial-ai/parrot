/**
 * Imports data/aktu/manifest.json into Cloudflare D1.
 *
 * Idempotent: rows are keyed by SHA-256, so re-running updates metadata and
 * never creates a second copy of a document.
 *
 * It imports academic METADATA only (document_assets). It deliberately does not
 * publish anything: approval state belongs to the administrator, and the five
 * course-structure documents awaiting review stay unpublished.
 *
 * Documents without a storage key are reported and skipped — importing a row
 * that claims to have a file which does not exist in R2 would be dishonest.
 *
 *   node scripts/data-aktu-import.mjs --local      # wrangler local D1 emulator
 *   node scripts/data-aktu-import.mjs --remote     # deployed D1 (needs auth)
 *   node scripts/data-aktu-import.mjs --dry-run    # write SQL, execute nothing
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const root = process.cwd();
const manifestPath = path.join(root, "data", "aktu", "manifest.json");
const outDir = path.join(root, "db", "d1-data");
const outPath = path.join(outDir, "aktu-import.sql");

const dryRun = process.argv.includes("--dry-run");
const remote = process.argv.includes("--remote");
const database = process.env.D1_DATABASE || "freeresources-dev";
const config = process.env.D1_CONFIG || "wrangler.jsonc";

if (!fs.existsSync(manifestPath)) {
  console.error("Missing data/aktu/manifest.json. Run `npm run data:aktu:export` first.");
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const documents = manifest.documents ?? [];

const quote = (value) => {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
};

const importable = [];
const skipped = [];

for (const document of documents) {
  if (!document.storageKey) {
    skipped.push({
      sha256: document.sha256,
      title: document.title,
      reason: "no storage key — export the manifest on the machine holding the acquisition database",
    });
    continue;
  }
  importable.push(document);
}

const statements = [
  "-- Generated by scripts/data-aktu-import.mjs. Do not edit by hand.",
  "-- Academic metadata only: no publishing, no approval changes.",
  "PRAGMA foreign_keys = ON;",
];

for (const document of importable) {
  statements.push(`
INSERT INTO document_assets (
  id, sha256, original_filename, mime_type, size_bytes, page_count,
  storage_key, source_url, source_domain, document_type, covers_semesters, fetched_at
) VALUES (
  ${quote(document.assetId)},
  ${quote(document.sha256)},
  ${quote(document.sourceFilename || document.storedFilename)},
  'application/pdf',
  ${Number(document.sizeBytes) || 0},
  ${Number(document.pageCount) || 0},
  ${quote(document.storageKey)},
  ${quote(document.sourceUrl)},
  ${quote(document.sourceDomain)},
  ${quote(document.documentType)},
  ${quote((document.coversSemesters || []).join(","))},
  NULL
)
ON CONFLICT(sha256) DO UPDATE SET
  original_filename = excluded.original_filename,
  size_bytes        = excluded.size_bytes,
  page_count        = excluded.page_count,
  storage_key       = excluded.storage_key,
  source_url        = excluded.source_url,
  source_domain     = excluded.source_domain,
  document_type     = excluded.document_type,
  covers_semesters  = excluded.covers_semesters;
`.trim());
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, `${statements.join("\n\n")}\n`, "utf8");

console.log(`Manifest        : ${documents.length} document(s)`);
console.log(`Importable      : ${importable.length}`);
console.log(`Skipped         : ${skipped.length}`);
for (const entry of skipped) console.log(`  - ${entry.title}: ${entry.reason}`);
console.log(`SQL written to  : ${path.relative(root, outPath)}`);

if (dryRun) {
  console.log("\n--dry-run: nothing was executed.");
  process.exit(0);
}

if (importable.length === 0) {
  console.log("\nNothing to import. Refusing to run an empty D1 command.");
  process.exit(0);
}

const target = remote ? "--remote" : "--local";
const command = `npx wrangler d1 execute ${database} ${target} --config ${config} --file=${outPath}`;
console.log(`\nRunning: ${command}`);

try {
  const output = execSync(command, { encoding: "utf8", stdio: "pipe" });
  console.log(output.trim());
  console.log(
    remote
      ? "\nImported into the REMOTE D1 database. Publication was NOT changed."
      : "\nImported into the LOCAL D1 emulator only. No Cloudflare account was touched.",
  );
} catch (error) {
  console.error("D1 import failed.");
  if (error.stdout) console.error(error.stdout.toString());
  if (error.stderr) console.error(error.stderr.toString());
  process.exit(1);
}
